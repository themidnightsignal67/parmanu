function makeGitLabTarget(platform: string, host: string): PlatformSweepTarget {
  return {
    platform,
    category: 'Developer & Code',
    urlFn: (h) => `https://${host}/${encodeURIComponent(h)}`,
    apiUrlFn: (h) => `https://${host}/api/v4/users?username=${encodeURIComponent(h)}`,
    extractJson: (data, handle) => {
      if (!Array.isArray(data) || data.length === 0) return { status: 'not_found' };
      const u = data
        .map(asObj)
        .find((x) => asStr(x?.username)?.toLowerCase() === handle.toLowerCase());
      if (!u) return { status: 'not_found' };
      return {
        status: 'found',
        id: u.id !== undefined ? String(u.id) : undefined,
        displayName: asStr(u.name) || asStr(u.username),
        avatarUrl: asStr(u.avatar_url),
        bio: asStr(u.bio),
        location: asStr(u.location),
        createdAt: asStr(u.created_at),
        url: asStr(u.web_url),
      };
    },
  };
}

function makeINaturalistTarget(): PlatformSweepTarget {
  return {
    platform: 'iNaturalist',
    category: 'Social & Community',
    urlFn: (h) => `https://www.inaturalist.org/people/${encodeURIComponent(h)}`,
    apiUrlFn: (h) => `https://api.inaturalist.org/v1/users/autocomplete?q=${encodeURIComponent(h)}`,
    extractJson: (data, handle) => {
      const results = asObj(data)?.results;
      if (!Array.isArray(results) || results.length === 0) return { status: 'not_found' };
      const u = results
        .map(asObj)
        .find((x) => asStr(x?.login)?.toLowerCase() === handle.toLowerCase());
      if (!u) return { status: 'not_found' };
      const obs = asNum(u.observations_count);
      return {
        status: 'found',
        id: u.id !== undefined ? String(u.id) : undefined,
        displayName: asStr(u.name) || asStr(u.login),
        avatarUrl: asStr(u.icon_url),
        createdAt: asStr(u.created_at),
        url: `https://www.inaturalist.org/people/${encodeURIComponent(asStr(u.login) || handle)}`,
        extraFields:
          typeof obs === 'number'
            ? [{ label: 'Observations', value: String(obs) }]
            : undefined,
      };
    },
  };
}

function makeHtml404Target(
  platform: string,
  category: PlatformSweepTarget['category'],
  urlTemplate: string,
  isSubdomain = false
): PlatformSweepTarget {
  return {
    platform,
    category,
    urlFn: (h) =>
      urlTemplate.replace(/handle/g, encodeURIComponent(isSubdomain ? h.toLowerCase() : h)),
    htmlCheck: {
      isSubdomainHost: isSubdomain,
      notFoundMarkers: [
        'page not found',
        'user not found',
        'profile not found',
        'this user does not exist',
        'account does not exist',
        '<title>404',
        'error 404',
      ],
      rejectRedirectSubstrings: ['/login', '/signin', '/signup', '/404'],
      foundMarkers: isSubdomain
        ? (_low, raw, h, finalUrlLower) =>
            raw.trim().length > 100 && finalUrlLower.includes(h)
        : (low, raw) =>
            raw.trim().length > 180 &&
            (low.includes('<title') || low.includes('og:title')),
    },
  };
}

