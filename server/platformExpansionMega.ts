function asObj(v: unknown): Record<string, unknown> | null {
  return v && typeof v === 'object' && !Array.isArray(v)
    ? (v as Record<string, unknown>)
    : null;
}

function asStr(v: unknown): string | undefined {
  return typeof v === 'string' && v.trim() ? v.trim() : undefined;
}

function asNum(v: unknown): number | undefined {
  return typeof v === 'number' && Number.isFinite(v) ? v : undefined;
}

function makeDiscourseTarget(
  platform: string,
  host: string,
  category: PlatformSweepTarget['category'] = 'Developer & Code'
): PlatformSweepTarget {
  const origin = new URL(`https://${host}`).origin;
  return {
    platform,
    category,
    urlFn: (h) => `https://${host}/u/${encodeURIComponent(h)}`,
    apiUrlFn: (h) => `https://${host}/u/${encodeURIComponent(h)}.json`,
    extractJson: (data) => {
      const user = asObj(asObj(data)?.user);
      if (!user || !user.username) return { status: 'not_found' };
      const tmpl = asStr(user.avatar_template);
      const avatarPath = tmpl ? tmpl.replace('{size}', '240') : undefined;
      const avatarUrl = avatarPath
        ? avatarPath.startsWith('http')
          ? avatarPath
          : `${origin}${avatarPath.startsWith('/') ? '' : '/'}${avatarPath}`
        : undefined;
      const extraFields: Array<{ label: string; value: string; copyable?: boolean }> = [];
      if (typeof user.trust_level === 'number') {
        extraFields.push({ label: 'Trust Level', value: String(user.trust_level) });
      }
      if (typeof user.badge_count === 'number' && user.badge_count > 0) {
        extraFields.push({ label: 'Badges', value: String(user.badge_count) });
      }
      return {
        status: 'found',
        id: user.id !== undefined ? String(user.id) : undefined,
        displayName: asStr(user.name) || asStr(user.username),
        avatarUrl,
        bio: asStr(user.bio_raw),
        location: asStr(user.location),
        createdAt: asStr(user.created_at),
        url: `https://${host}/u/${encodeURIComponent(asStr(user.username) || '')}`,
        extraFields: extraFields.length > 0 ? extraFields : undefined,
      };
    },
  };
}

