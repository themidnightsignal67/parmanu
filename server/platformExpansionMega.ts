function makePeerTubeTarget(platform: string, host: string): PlatformSweepTarget {
  const origin = `https://${host}`;
  return {
    platform,
    category: 'Social & Community',
    urlFn: (h) => `${origin}/a/${encodeURIComponent(h)}`,
    apiUrlFn: (h) => `${origin}/api/v1/accounts/${encodeURIComponent(h)}`,
    extractJson: (data) => {
      const obj = asObj(data);
      if (!obj || !obj.name) return { status: 'not_found' };
      const avatars = Array.isArray(obj.avatars) ? obj.avatars : [];
      const firstAv = asObj(avatars[0]);
      const avPath = asStr(firstAv?.path) || asStr(asObj(obj.avatar)?.path);
      return {
        status: 'found',
        id: obj.id !== undefined ? String(obj.id) : undefined,
        displayName: asStr(obj.displayName) || asStr(obj.name),
        avatarUrl: avPath ? (avPath.startsWith('http') ? avPath : `${origin}${avPath}`) : undefined,
        bio: asStr(obj.description),
        followers: asNum(obj.followersCount),
        createdAt: asStr(obj.createdAt),
        url: asStr(obj.url),
      };
    },
  };
}

