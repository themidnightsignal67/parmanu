export function buildMegaEmailProbes(email: string): PlatformSweepTarget[] {
  const cleanEmail = email.trim();
  const liveVerifiedBugzillas: PlatformSweepTarget[] = [
    makeBugzillaEmailProbe('RedHat Bugzilla', 'bugzilla.redhat.com', cleanEmail),
    makeBugzillaEmailProbe('SUSE Bugzilla', 'bugzilla.suse.com', cleanEmail),
    makeBugzillaEmailProbe('Gentoo Bugzilla', 'bugs.gentoo.org', cleanEmail),
    makeBugzillaEmailProbe(
      'LibreOffice Bugzilla',
      'bugs.documentfoundation.org',
      cleanEmail
    ),
    makeBugzillaEmailProbe('KDE Bugzilla', 'bugs.kde.org', cleanEmail),
    makeBugzillaEmailProbe('Mozilla Bugzilla', 'bugzilla.mozilla.org', cleanEmail),
    makeBugzillaEmailProbe('WebKit Bugzilla', 'bugs.webkit.org', cleanEmail),
  ];

  const bulkProbes = MEGA_EMAIL_SITES.map((seed) =>
    makeBulkEmailEndpointProbe(seed, cleanEmail)
  );

  return [...liveVerifiedBugzillas, ...bulkProbes];
}
