const TRAI_2_DIGIT_HINTS: Array<{ match: RegExp; carrier: string; circleKey: keyof typeof CIRCLE_GEO }> = [
  { match: /^(60|62|63|70|72|73|74|75|76|77|78|79|80|81|82|83|84|85|86|87|88|89|91|93)/, carrier: 'Reliance Jio / Airtel / Vi (TRAI 4G/5G Series)', circleKey: 'PAN_INDIA' },
  { match: /^92/, carrier: 'Tata Teleservices / MNP (TRAI 92xx Series)', circleKey: 'PAN_INDIA' },
  { match: /^94/, carrier: 'BSNL Mobile (TRAI 94xx Series)', circleKey: 'PAN_INDIA' },
  { match: /^[6-9]/, carrier: 'Indian GSM Mobile (Airtel / Vi / Jio)', circleKey: 'PAN_INDIA' },
];

export function resolveIndianTelecomSeries(national10: string): IndianTelecomInfo | null {
  if (!/^[6-9]\d{9}$/.test(national10)) return null;
  const p4 = national10.slice(0, 4);
  const hit4 = TRAI_4_DIGIT_PREFIXES[p4];
  if (hit4) {
    const [carrier, geoKey] = hit4;
    const geo = CIRCLE_GEO[geoKey] || CIRCLE_GEO.PAN_INDIA;
    return {
      carrier,
      circle: geo.circle,
      city: geo.city,
      lat: geo.lat,
      lng: geo.lng,
      prefixMatched: p4,
      note: 'Original TRAI MSC allotment (subject to MNP porting)',
    };
  }

  for (const h of TRAI_2_DIGIT_HINTS) {
    if (h.match.test(national10)) {
      const geo = CIRCLE_GEO[h.circleKey];
      return {
        carrier: h.carrier,
        circle: geo.circle,
        city: geo.city,
        lat: geo.lat,
        lng: geo.lng,
        prefixMatched: national10.slice(0, 3),
        note: 'TRAI national series classification (subject to MNP porting)',
      };
    }
  }

  return null;
}
